// Generates src/styles/tokens.css from design/tokens.json (theme: atelier).
// Run with `npm run tokens`. The output is committed; a test fails on drift.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const THEME = 'atelier'
const here = dirname(fileURLToPath(import.meta.url))
export const tokensJsonPath = resolve(here, '../../../design/tokens.json')
export const tokensCssPath = resolve(here, '../src/styles/tokens.css')

// Values the studio needs that tokens.json does not have yet (design/studio/shell.md,
// "Token gaps"). Each is an alias of a real token. A gap is emitted only while the
// token is missing, so the day it lands in tokens.json this entry stops being used.
export const GAP_STAND_INS = {
    'color.overlay': 'color.image_scrim',
    'layout.nav_width': 'max-content',
    'layout.dialog_width': 'layout.content_width',
    'color.disabled_text': 'color.text_muted',
    'color.disabled_border': 'color.border',
    'border_width.indicator': 'border_width.focus',
}

const META = new Set(['name', 'description', 'color_scheme'])

export function varName(path) {
    return `--hs-${path.replaceAll('_', '-').replaceAll('.', '-')}`
}

function flatten(group, prefix = '') {
    const out = []
    for (const [key, value] of Object.entries(group)) {
        if (!prefix && META.has(key)) continue
        const path = prefix ? `${prefix}.${key}` : key
        if (typeof value === 'object' && value !== null) out.push(...flatten(value, path))
        else out.push([path, String(value)])
    }
    return out
}

export function breakpoints(tokens, theme = THEME) {
    return tokens.themes[theme].breakpoint
}

export function buildTokensCss(tokens, theme = THEME) {
    const t = tokens.themes[theme]
    const entries = flatten(t)
    const known = new Set(entries.map(([p]) => p))
    const lines = entries.map(([p, v]) => `    ${varName(p)}: ${v};`)
    const gaps = []
    for (const [path, target] of Object.entries(GAP_STAND_INS)) {
        if (known.has(path)) continue
        gaps.push(
            `    ${varName(path)}: ${known.has(target) ? `var(${varName(target)})` : target};`,
        )
    }
    return [
        '/* Generated by scripts/tokens.mjs from design/tokens.json. Do not edit; run `npm run tokens`. */',
        `/* Theme: ${theme}. Media queries cannot use custom properties: write breakpoint(md), see README. */`,
        ':root {',
        `    color-scheme: ${t.color_scheme};`,
        ...lines,
        ...(gaps.length
            ? [
                  '',
                  '    /* Stand-ins for tokens that do not exist yet (shell.md, Token gaps). */',
                  ...gaps,
              ]
            : []),
        '}',
        '',
    ].join('\n')
}

// Replaces breakpoint(sm|md|lg) in a CSS string with the token value.
export function replaceBreakpoints(css, bps) {
    return css.replace(/breakpoint\(\s*([a-z]+)\s*\)/g, (match, name) => {
        if (!(name in bps)) throw new Error(`Unknown breakpoint "${name}"`)
        return bps[name]
    })
}

// PostCSS plugin: `@media (min-width: breakpoint(md))` becomes the token value, because
// custom properties cannot be used inside media queries.
export function breakpointPlugin(
    bps = breakpoints(JSON.parse(readFileSync(tokensJsonPath, 'utf8'))),
) {
    return {
        postcssPlugin: 'hivesite-breakpoints',
        AtRule: {
            media(rule) {
                if (rule.params.includes('breakpoint(')) {
                    rule.params = replaceBreakpoints(rule.params, bps)
                }
            },
        },
    }
}
breakpointPlugin.postcss = true

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const tokens = JSON.parse(readFileSync(tokensJsonPath, 'utf8'))
    writeFileSync(tokensCssPath, buildTokensCss(tokens))
    console.log('wrote src/styles/tokens.css')
}

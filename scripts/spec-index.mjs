#!/usr/bin/env node
// Validates API specs and generates specs/README.md.
//
//   node spec-index.mjs [specsDir]          write specs/README.md
//   node spec-index.mjs [specsDir] --check  fail if specs are invalid or README.md is stale
//
// A spec is any specs/<domain>/*.md file with a front matter block (see templates/specs/STYLE.md).
// No dependencies: the front matter is a flat "key: value" list, arrays as [a, b].

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const STATUSES = ["draft", "in review", "approved", "built"];
const REQUIRED = ["id", "title", "domain", "status", "owner", "version"];
const ID = /^API-\d{3}$/;

const args = process.argv.slice(2);
const check = args.includes("--check");
const root = args.find(a => !a.startsWith("--")) ?? "specs";

if (!existsSync(root)) {
  console.error(`spec-index: no ${root}/ folder`);
  process.exit(1);
}

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith(".md") ? [p] : [];
  });
}

function parseValue(raw) {
  const v = raw.replace(/\s+#.*$/, "").trim();
  if (v.startsWith("[") && v.endsWith("]")) {
    return v.slice(1, -1).split(",").map(s => s.trim()).filter(Boolean)
      .map(s => (/^\d+$/.test(s) ? Number(s) : s));
  }
  if (/^\d+$/.test(v)) return Number(v);
  return v.replace(/^["']|["']$/g, "");
}

function parse(file) {
  const text = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return null;
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([a-z_]+):\s*(.*)$/);
    if (kv) meta[kv[1]] = parseValue(kv[2]);
  }
  const oq = m[2].split(/^## /m).find(s => s.startsWith("Open questions"));
  const questions = oq
    ? oq.split("\n").slice(1).map(l => l.match(/^\s*-\s+(.*)$/)?.[1]?.trim()).filter(q => q && q.toLowerCase() !== "none")
    : [];
  return { file: relative(root, file).split(sep).join("/"), meta, questions };
}

const errors = [];
const specs = [];
for (const file of walk(root)) {
  if (/(^|[\\/])(README|STYLE|TEMPLATE)\.md$/i.test(file)) continue;
  const spec = parse(file);
  if (!spec) { errors.push(`${file}: missing front matter`); continue; }
  specs.push(spec);
}

const ids = new Map();
for (const s of specs) {
  const { meta, file } = s;
  for (const k of REQUIRED) if (meta[k] === undefined || meta[k] === "") errors.push(`${file}: missing "${k}"`);
  if (meta.id && !ID.test(meta.id)) errors.push(`${file}: id "${meta.id}" must look like API-001`);
  if (meta.id && ids.has(meta.id)) errors.push(`${file}: duplicate id ${meta.id} (also in ${ids.get(meta.id)})`);
  if (meta.id) ids.set(meta.id, file);
  if (meta.status && !STATUSES.includes(meta.status)) errors.push(`${file}: status "${meta.status}" is not one of ${STATUSES.join(", ")}`);
  const folder = file.split("/")[0];
  if (meta.domain && folder !== file && folder !== meta.domain) errors.push(`${file}: domain "${meta.domain}" does not match folder "${folder}"`);
  if (["approved", "built"].includes(meta.status) && s.questions.length) errors.push(`${file}: ${meta.status} spec still has open questions`);
}
for (const s of specs) {
  for (const dep of [].concat(s.meta.depends_on ?? [])) {
    if (!ids.has(dep)) errors.push(`${s.file}: depends on unknown spec ${dep}`);
  }
}

const byId = (a, b) => String(a.meta.id).localeCompare(String(b.meta.id));
const row = s => `| [${s.meta.id}](${s.file}) | ${s.meta.title} | ${s.meta.status} | ${[].concat(s.meta.stories ?? []).map(n => `#${n}`).join(", ") || "—"} | ${[].concat(s.meta.depends_on ?? []).join(", ") || "—"} |`;
const head = "| Spec | Title | Status | Stories | Depends on |\n|---|---|---|---|---|";

let out = "# API specs\n\n<!-- Generated by spec-index.mjs. Do not edit by hand. -->\n\n";
const domains = [...new Set(specs.map(s => s.meta.domain))].sort();
for (const d of domains) {
  out += `## ${d}\n\n${head}\n${specs.filter(s => s.meta.domain === d).sort(byId).map(row).join("\n")}\n\n`;
}
out += "## By status\n\n";
for (const st of STATUSES) {
  const list = specs.filter(s => s.meta.status === st).sort(byId);
  out += `- **${st}** (${list.length}): ${list.map(s => s.meta.id).join(", ") || "—"}\n`;
}
out += "\n## Open questions\n\n";
const open = specs.filter(s => s.questions.length).sort(byId);
out += open.length ? open.map(s => s.questions.map(q => `- ${s.meta.id}: ${q}`).join("\n")).join("\n") + "\n" : "None.\n";
if (!specs.length) out = "# API specs\n\n<!-- Generated by spec-index.mjs. Do not edit by hand. -->\n\nNo specs yet.\n";

const readme = join(root, "README.md");
if (check) {
  const current = existsSync(readme) ? readFileSync(readme, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== out) errors.push(`${readme} is out of date: run node scripts/spec-index.mjs`);
} else {
  writeFileSync(readme, out);
}

if (errors.length) {
  console.error(errors.map(e => `✗ ${e}`).join("\n"));
  process.exit(1);
}
console.log(`spec-index: ${specs.length} spec(s) OK${check ? "" : `, wrote ${readme}`}`);
